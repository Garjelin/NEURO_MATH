"""DOCX для практической работы №4 (вариант 5)."""

from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt


def _p(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def _code_block(doc: Document, lines: str) -> None:
    p = doc.add_paragraph()
    run = p.add_run(lines.strip("\n"))
    run.font.name = "Courier New"
    run.font.size = Pt(10)
    p.paragraph_format.left_indent = Inches(0.25)


def _add_figure(doc: Document, image_path: Path | None, caption: str, width_inches: float = 5.8) -> None:
    if image_path is not None and image_path.is_file():
        doc.add_picture(str(image_path), width=Inches(width_inches))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in cap.runs:
        run.italic = True


def _add_console_placeholder(doc: Document, title: str, instruction: str) -> None:
    doc.add_heading(title, level=3)
    _p(doc, instruction)
    doc.add_paragraph()
    doc.add_paragraph()


def build_practice04_docx(
    report_path: Path,
    data: dict,
    plot_task1_tree: Path | None = None,
    plot_task1_pred: Path | None = None,
    plot_task2_tree: Path | None = None,
    plot_task2_bar: Path | None = None,
    source_file_hint: str = "neuro_math_Yakimov_var5/task_4/practice04.py",
) -> None:
    report_path.parent.mkdir(parents=True, exist_ok=True)

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    t1 = data["task1"]
    t2 = data["task2"]
    t3 = data["task3"]

    doc.add_heading("Практическая работа №4. Вариант 5", level=1)
    _p(
        doc,
        "Цель практической работы — закрепить навыки построения регрессионных моделей "
        "на основе дерева решений и навыки анализа вычислительного графа с ручным "
        "обратным распространением производных. Вариант 5 включает три независимых "
        "подзадачи: две табличные задачи регрессии и одну задачу дифференцирования "
        "сложной функции по входным переменным.",
    )
    _p(
        doc,
        "Ниже материал структурирован по формату, принятому в предыдущих отчётах: "
        "для каждого задания отдельно описаны постановка, исходные данные, методика, "
        "полученные результаты, интерпретация и место для скриншота консольного вывода.",
    )

    # -----------------------------
    # ЗАДАНИЕ 1
    # -----------------------------
    doc.add_heading("Задание 1. Дерево решений по таблице 4.3", level=2)
    _p(doc, "1) Постановка задачи.")
    _p(
        doc,
        "По таблице 4.3 требуется построить модель зависимости Y от признака x. "
        "Согласно таблице вариантов (4.4), для варианта 5 в обучение включаются строки "
        "7, 8, 9 и 10, а остальные строки используются для логического теста. "
        "Так как целевая переменная непрерывная, задача решается в регрессионной постановке, "
        "а контроль качества выполняется по среднеквадратичной ошибке MSE.",
    )

    _p(doc, "2) Используемые данные.")
    _p(
        doc,
        f"Строки обучения (нумерация по заданию): {t1['train_rows']}. "
        f"Строки теста: {t1['test_rows']}.",
    )
    _p(
        doc,
        "Особенность подвыборки: встречаются пары с одинаковым x и различными Y. "
        "Это означает, что в данных присутствует неоднозначность с точки зрения "
        "детерминированной функции Y = f(x), поэтому дерево в ряде листьев "
        "вынуждено использовать усреднение целевых значений.",
    )

    _p(doc, "3) Модель и алгоритм обучения.")
    _p(
        doc,
        "Использована модель `DecisionTreeRegressor` из библиотеки scikit-learn. "
        "Для задания 1 применён критерий `squared_error`, что соответствует "
        "минимизации среднеквадратичной ошибки при поиске оптимальных разбиений. "
        "Дерево автоматически выбирает пороги по x и строит кусочно-постоянную "
        "аппроксимацию целевой переменной.",
    )

    _p(doc, "4) Результаты обучения и тестирования.")
    _p(
        doc,
        f"MSE на обучении: {t1['mse_train']:.6g}. "
        f"MSE на тесте: {t1['mse_test']:.6g}. "
        "Ненулевая ошибка на обучающей выборке в данном случае является ожидаемой: "
        "при одинаковом x и разных Y модель физически не может предсказать сразу оба "
        "значения без ошибки. На тесте MSE показывает, насколько хорошо полученная "
        "структура дерева переносится на оставшиеся строки таблицы.",
    )

    _p(doc, "5) Иллюстрации к заданию 1.")
    _add_figure(
        doc,
        plot_task1_tree,
        "Рисунок 1 — Дерево решений для задания 1.",
    )
    _add_figure(
        doc,
        plot_task1_pred,
        "Рисунок 2 — Точки train/test и предсказание дерева по оси x.",
    )

    _add_console_placeholder(
        doc,
        "Рисунок 3 — Скрин консоли для задания 1 (вставить вручную)",
        "Вставьте скриншот терминала после запуска `python -m neuro_math_Yakimov_var5.task_4.practice04`, "
        "чтобы были видны блок [1/3], список строк обучения/теста и значения MSE на train/test. "
        "Рекомендуется, чтобы на скриншоте полностью читались подписи метрик и номера строк.",
    )

    # -----------------------------
    # ЗАДАНИЕ 2
    # -----------------------------
    doc.add_heading("Задание 2. Дерево по двум бинарным признакам (таблица 4.5)", level=2)
    _p(doc, "1) Постановка задачи.")
    _p(
        doc,
        "Входы: бинарные признаки x и z. Для варианта 5 обучение выполняется на строках "
        "2, 3, 5, 8, 9, 10 таблицы 4.5, тест — на остальных строках. "
        "Качество на тесте оценивается метрикой MAE как средней абсолютной ошибкой "
        "между фактическими и предсказанными значениями.",
    )

    _p(doc, "2) Параметры модели.")
    _p(
        doc,
        f"Использованный критерий дерева в sklearn: {t2['tree_criterion']}. "
        "Если доступен критерий `absolute_error`, обучение проводится напрямую "
        "в постановке минимизации абсолютной ошибки. Это позволяет лучше согласовать "
        "процедуру построения дерева с метрикой, требуемой в задании.",
    )
    _p(
        doc,
        "Поскольку признаки бинарные (0/1), каждое разбиение дерева имеет понятную "
        "интерпретацию: модель отделяет группы наблюдений по значениям x и z и назначает "
        "в листе характерный уровень Y для соответствующей комбинации признаков.",
    )

    _p(doc, "3) Результаты по метрикам.")
    _p(
        doc,
        f"MAE на обучении: {t2['mae_train']:.6g}. "
        f"MAE на тесте: {t2['mae_test']:.6g}. "
        "Интерпретация MAE: это средний модуль отклонения прогноза от факта. "
        "Чем меньше MAE, тем точнее модель в абсолютных единицах Y.",
    )
    _p(
        doc,
        "Следует учитывать, что в обучающих строках могут встречаться одинаковые пары (x, z) "
        "с различными целевыми значениями Y. В такой ситуации дерево неизбежно усредняет "
        "ответ внутри листа, поэтому нулевая ошибка достигается не всегда даже на train.",
    )

    _p(doc, "4) Иллюстрации к заданию 2.")
    _add_figure(
        doc,
        plot_task2_tree,
        "Рисунок 4 — Дерево решений для задания 2.",
    )
    _add_figure(
        doc,
        plot_task2_bar,
        "Рисунок 5 — Сравнение фактических и предсказанных Y на тесте задания 2.",
    )

    _add_console_placeholder(
        doc,
        "Рисунок 6 — Скрин консоли для задания 2 (вставить вручную)",
        "Вставьте скриншот терминала с блоком [2/3], где отображены строки обучения/теста, "
        "критерий дерева и значения MAE на обучении и тесте. На скриншоте должно быть видно, "
        "что используется именно вариант 5 (строки 2,3,5,8,9,10).",
    )

    # -----------------------------
    # ЗАДАНИЕ 3
    # -----------------------------
    doc.add_heading("Задание 3. Граф вычислений и обратное распространение", level=2)
    _p(doc, "1) Функция и область определения.")
    _p(
        doc,
        "Для варианта 5: f(x, y) = exp(x^y) - cos(x/y) + 1/sin(x+y), где x^y — степень основания x "
        "показателем y. Ограничения области определения: x > 0 (для вещественной степени и "
        "производной ∂(x^y)/∂y = x^y ln x), y != 0 (узел x/y), sin(x+y) != 0 (узел 1/sin(x+y)). "
        "Перед вычислением программа проверяет эти условия.",
    )

    _p(doc, "2) Структура вычислительного графа.")
    _code_block(
        doc,
        "n1 = x ** y        # x в степени y\n"
        "n2 = exp(n1)\n"
        "n3 = x / y\n"
        "n4 = cos(n3)\n"
        "n5 = x + y\n"
        "n6 = sin(n5)\n"
        "n7 = 1 / n6\n"
        "f  = n2 - n4 + n7",
    )

    _p(doc, "3) Прямой и обратный проход.")
    _p(
        doc,
        "В программе последовательно вычисляются значения всех промежуточных узлов (прямой проход), "
        "после чего по правилу цепочки вычисляются аналитические градиенты ∂f/∂x и ∂f/∂y "
        "(обратный проход). При обратном проходе учитывается вклад каждой ветви графа в "
        "конечные производные по x и y. Для узла n1 = x^y используются стандартные формулы "
        "∂n1/∂x = y·x^(y−1) и ∂n1/∂y = x^y·ln(x) при x > 0. Для проверки корректности "
        "аналитические градиенты сопоставляются с численными производными, вычисленными "
        "симметричной конечно-разностной схемой.",
    )
    _p(
        doc,
        "Если аналитические и численные значения близки, это подтверждает, что формулы "
        "дифференцирования и порядок обхода графа реализованы корректно.",
    )

    doc.add_heading("4) Таблица результатов для контрольных точек", level=3)
    table = doc.add_table(rows=1, cols=6)
    hdr = table.rows[0].cells
    hdr[0].text = "x"
    hdr[1].text = "y"
    hdr[2].text = "f"
    hdr[3].text = "∂f/∂x (анал.)"
    hdr[4].text = "∂f/∂y (анал.)"
    hdr[5].text = "Проверка (числ.)"
    for row in t3["points"]:
        x, y = row["point"]
        cells = table.add_row().cells
        cells[0].text = f"{x:g}"
        cells[1].text = f"{y:g}"
        cells[2].text = f"{row['f']:.6f}"
        cells[3].text = f"{row['df_dx_analytic']:.6f}"
        cells[4].text = f"{row['df_dy_analytic']:.6f}"
        cells[5].text = f"dx={row['df_dx_numeric']:.6f}, dy={row['df_dy_numeric']:.6f}"

    _add_console_placeholder(
        doc,
        "Рисунок 7 — Скрин консоли для задания 3 (вставить вручную)",
        "Вставьте скриншот терминала с блоком [3/3], чтобы были видны значения узлов n1...n7, "
        "значение f и сравнение аналитических/численных градиентов для всех контрольных точек.",
    )

    doc.add_heading("Вывод", level=2)
    _p(
        doc,
        "В рамках практической работы последовательно выполнены все этапы варианта 5: "
        "построены регрессионные деревья решений для двух табличных постановок, "
        "получены количественные оценки качества по MSE и MAE, а также выполнен "
        "детальный анализ вычислительного графа функции с ручным прямым и обратным проходом.",
    )
    _p(
        doc,
        "Полученные результаты показывают, что дерево решений корректно обрабатывает "
        "малые и неоднозначные выборки, а проверка градиентов через численное дифференцирование "
        "подтверждает правильность реализации backpropagation для выбранной функции.",
    )

    doc.add_heading("Ссылка на исходный код", level=2)
    _p(
        doc,
        f"Рабочий скрипт: `{source_file_hint}`. "
        "Генератор отчёта расположен в каталоге `report_generator/`.",
    )

    doc.save(report_path)
