"""Сборка подробного DOCX для практической работы №1 (вариант 5), по образцу методички."""

from __future__ import annotations

from pathlib import Path

import numpy as np
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt

from assignments.practice01 import OptResult


def _p(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def _code_block(doc: Document, lines: str) -> None:
    p = doc.add_paragraph()
    run = p.add_run(lines.strip("\n"))
    run.font.name = "Courier New"
    run.font.size = Pt(10)
    p.paragraph_format.left_indent = Inches(0.25)


def _add_figure(doc: Document, image_path: Path | None, caption: str, width_inches: float = 5.8) -> None:
    if image_path is not None and image_path.is_file():
        doc.add_picture(str(image_path), width=Inches(width_inches))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in cap.runs:
        run.italic = True


def _results_table_task_a(doc: Document, results: list[OptResult]) -> None:
    table = doc.add_table(rows=1, cols=4)
    hdr = table.rows[0].cells
    hdr[0].text = "Метод"
    hdr[1].text = "x*"
    hdr[2].text = "f(x*)"
    hdr[3].text = "Итераций (шагов)"
    for r in results:
        row = table.add_row().cells
        row[0].text = r.method
        row[1].text = f"{r.point[0]:.8f}"
        row[2].text = f"{r.value:.8f}"
        row[3].text = str(r.iterations)


def _results_table_task_b(doc: Document, results: list[OptResult]) -> None:
    table = doc.add_table(rows=1, cols=4)
    hdr = table.rows[0].cells
    hdr[0].text = "Метод"
    hdr[1].text = "x* = (x1*, x2*)"
    hdr[2].text = "f(x*)"
    hdr[3].text = "Итераций (шагов)"
    for r in results:
        row = table.add_row().cells
        row[0].text = r.method
        row[1].text = f"({r.point[0]:.8f}; {r.point[1]:.8f})"
        row[2].text = f"{r.value:.8f}"
        row[3].text = str(r.iterations)


def build_practice01_docx(
    report_path: Path,
    task_a_results: list[OptResult],
    task_b_results: list[OptResult],
    add_w: np.ndarray,
    add_h: float,
    add_preds: list[int],
    plot_a: Path | None = None,
    plot_b: Path | None = None,
    source_file_hint: str = "assignments/practice01.py",
) -> None:
    report_path.parent.mkdir(parents=True, exist_ok=True)

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    # --- Титул и цель (по аналогии с «Задание №1» в образце) ---
    doc.add_heading("Практическая работа №1. Вариант 5", level=1)
    _p(
        doc,
        "Задание: смоделировать процесс поиска точки минимума для функции одной переменной "
        "(задание А) и функции двух переменных (задание Б) с использованием методов "
        "градиентного спуска, покоординатного спуска и адаптивного градиентного спуска. "
        "Дополнительно — определить параметры w1, w2 и смещение h простого нейрона "
        "(персептрона) по учебной выборке «вес — рост — пол».",
    )
    _p(
        doc,
        "Последовательность изложения решения включает пять этапов, аналогичных структуре "
        "примера из методических материалов: подготовка и формализация задачи; выбор "
        "«архитектуры» алгоритма (набора методов и их параметров); выполнение итерационного "
        "процесса минимизации; анализ качества и сопоставление результатов на тестовых "
        "сценариях (сравнение методов, графики сходимости); заключительное моделирование "
        "и дополнительное задание.",
    )

    doc.add_heading("Постановка задачи (вариант 5)", level=2)
    _p(
        doc,
        "Задание А. Требуется найти точку минимума функции одной переменной "
        "f(x) = x³ − 3 sin(x). Согласно таблице вариантов, начальная точка задаётся на "
        "отрезке [0; 1]. В работе в качестве стартового приближения выбрано x₀ = 0 — "
        "левая граница допустимого интервала; при необходимости исследования можно "
        "повторить расчёт для других x₀ ∈ [0; 1] и сравнить траектории спуска.",
    )
    _p(
        doc,
        "Градиент (производная) для задания А: f′(x) = 3x² − 3 cos(x). Условие первого "
        "порядка f′(x) = 0 определяет стационарные точки; для численного поиска минимума "
        "используются итерационные методы первого порядка, не требующие явного решения "
        "трансцендентного уравнения.",
    )
    _p(
        doc,
        "Задание Б. Требуется найти точку минимума функции двух переменных "
        "f(x₁, x₂) = 2x₁² + 2x₂² + 2x₁x₂ − 14x₁ − 12x₂ + 29. Начальная точка согласно "
        "варианту: (x₁⁽⁰⁾, x₂⁽⁰⁾) = (−1; 4).",
    )
    _p(
        doc,
        "Вектор градиента: ∇f(x₁, x₂) = (4x₁ + 2x₂ − 14; 2x₁ + 4x₂ − 12). Для квадратичной "
        "формы положение минимума можно также проверить аналитически: решение системы "
        "∇f = 0 даёт x₁* = 8/3, x₂* = 5/3 и f_min = 1/3. Численные методы должны "
        "сходиться к этому минимуму (с точностью, определяемой критериями останова).",
    )

    # --- Этап 1 ---
    doc.add_heading("1-й этап: подготовка данных и формализация эксперимента", level=2)
    _p(
        doc,
        "На первом этапе, по аналогии с примером из методички, необходимо определить "
        "размерность задачи, диапазоны величин и способ представления результатов. "
        "В отличие от задачи аппроксимации зависимости Y = a / (b + x^c), где формировались "
        "матрицы входов и эталонов размерности N×M и 3×M, в нашем случае «данными» являются "
        "скалярная или векторная переменная состояния (x для задания А и (x₁, x₂) для задания Б), "
        "а также значение целевой функции f и её градиент на каждой итерации.",
    )
    _p(
        doc,
        "Для задания А пространство поиска одномерное: на каждом шаге алгоритм хранит "
        "текущее приближение x_k и последовательность значений f(x_k) для последующего "
        "построения графика сходимости (аналог графика ошибки обучения по эпохам в примере "
        "с нейросетью).",
    )
    _p(
        doc,
        "Для задания Б пространство двумерное: хранятся пары (x₁, x₂)_k и значения "
        "f(x₁, x₂)_k. Норма градиента ‖∇f‖ используется как индикатор близости к стационарной "
        "точке; при ‖∇f‖ < ε итерации прекращаются.",
    )
    _p(
        doc,
        "Дополнительное задание использует табличную выборку объектов A₁…A₃ с признаками "
        "«масса тела (кг)» и «рост (см)» и бинарной меткой пола (1 — мужской, 0 — женский). "
        "Строка A₄ в задании предполагает включение собственных данных студента; в отчёт "
        "следует вставить актуальные числа и при необходимости пересчитать веса.",
    )

    # --- Этап 2 ---
    doc.add_heading("2-й этап: выбор методов оптимизации («создание модели»)", level=2)
    _p(
        doc,
        "Во втором этапе, по смыслу соответствующем блоку «создание сети» в образце, "
        "задаётся набор используемых процедур минимизации. В работе применяются три метода:",
    )
    _p(
        doc,
        "1) Градиентный спуск. На каждой итерации вычисляется градиент ∇f в текущей точке "
        "и выполняется шаг x_{k+1} = x_k − η ∇f(x_k). В реализации используется дробление шага "
        "(backtracking): если очередной шаг не уменьшает f, шаг η уменьшается вдвое до "
        "достижения убывания функции либо до исчерпания нижней границы шага.",
    )
    _p(
        doc,
        "2) Покоординатный спуск. Вектор обновляется покомпонентно: для каждой координаты "
        "выполняется одномерный спуск вдоль соответствующей частной производной при "
        "фиксированных остальных переменных. Такой подход часто применяют, когда полный "
        "градиентный шаг неудобен или когда структура задачи «почти разделяема» по координатам.",
    )
    _p(
        doc,
        "3) Адаптивный градиентный спуск (вариант Adagrad). Накопительные суммы квадратов "
        "компонент градиента G_i используются для индивидуальной подстройки эффективного шага "
        "по каждой координате: η_i = η / (√(G_i) + ε). Это снижает чувствительность к выбору "
        "глобальной скорости обучения по сравнению с классическим градиентным спуском с "
        "фиксированным η.",
    )
    _p(
        doc,
        "Реализация всех трёх методов содержится в модуле исходного кода; ключевые "
        "фрагменты именуются gradient_descent, coordinate_descent, adaptive_gradient_descent.",
    )
    _code_block(
        doc,
        """# Пример вызова (см. полный код в файле исходников):
task_a_results = [
    gradient_descent(f_a, grad_a, x0_a, lr=0.05),
    coordinate_descent(f_a, grad_a, x0_a, lr=0.1),
    adaptive_gradient_descent(f_a, grad_a, x0_a, lr=0.8),
]""",
    )

    # --- Этап 3 ---
    doc.add_heading("3-й этап: параметры итерационного процесса («обучение»)", level=2)
    _p(
        doc,
        "Третий этап соответствует настройке параметров обучения в примере с MATLAB "
        "(performFcn, goal, epochs). В нашей постановке роль функционала ошибки выполняет "
        "сама целевая функция f: на каждой итерации отслеживается убывание f(x) или f(x₁, x₂).",
    )
    _p(
        doc,
        "Основные гиперпараметры: начальные скорости обучения η (различаются для методов и "
        "для задач А и Б — см. код), допуск по норме градиента для останова, максимальное число "
        "итераций, нижняя граница шага при дроблении. При достижении ‖∇f‖ < 10⁻⁷ итерации "
        "завершаются; при невозможности уменьшить f на шаге процесс также останавливается.",
    )
    _p(
        doc,
        "Для дополнительного задания используется правило обучения персептрона Розенблатта "
        "с нормировкой признаков по столбцам (вычитание среднего, деление на стандартное "
        "отклонение) для устойчивости сходимости при разном масштабе «кг» и «см».",
    )

    # --- Этап 4 ---
    doc.add_heading("4-й этап: результаты и анализ сходимости («тестирование»)", level=2)
    _p(
        doc,
        "На четвёртом этапе, аналогично разделу тестирования в образце, представляются "
        "численные результаты и графическая диагностика. Ниже приведены таблицы найденных "
        "минимумов для заданий А и Б по каждому методу (значения получены программно при "
        "формировании отчёта).",
    )

    doc.add_heading("Таблица 1. Результаты минимизации (задание А)", level=3)
    _results_table_task_a(doc, task_a_results)

    doc.add_heading("Таблица 2. Результаты минимизации (задание Б)", level=3)
    _results_table_task_b(doc, task_b_results)

    _p(
        doc,
        "Графики зависимости значения функции от номера итерации иллюстрируют скорость "
        "снижения f и позволяют сравнить методы визуально (ср. с графиком ошибки по эпохам "
        "в примере с train).",
    )

    _add_figure(
        doc,
        plot_a,
        "Рисунок 1 — Сходимость методов для задания А (f(x) = x³ − 3 sin x).",
    )
    _add_figure(
        doc,
        plot_b,
        "Рисунок 2 — Сходимость методов для задания Б (квадратичная функция двух переменных).",
    )

    _p(
        doc,
        "Интерпретация. Для задания Б все три метода должны приближаться к аналитическому "
        "минимуму (8/3; 5/3) с f_min = 1/3; расхождения в числе итераций отражают разную "
        "эффективность на данной квадратичной поверхности. Для задания А сравнение методов "
        "показывает, насколько быстро каждый из них уменьшает f при выбранных η и стратегии "
        "шага.",
    )

    doc.add_heading("Рисунок 3 — скриншот консоли (вставить самостоятельно)", level=3)
    _p(
        doc,
        "Ниже по вертикали оставлено место под иллюстрацию: сюда нужно вставить скриншот "
        "терминала после запуска рабочей программы (без генератора отчёта).",
    )
    _code_block(
        doc,
        "# Из корня репозитория NEURO_MATH выполните:\n"
        "python -m assignments.practice01",
    )
    _p(
        doc,
        "Как вставить рисунок в Word: меню «Вставка» → «Рисунки» → «Это устройство» → "
        "выберите сохранённый файл (например console_practice01.png). На скриншоте должно "
        "быть видно: блоки [1/4]…[4/4], табличный вывод по методам для А и Б, дополнительное "
        "задание и пути к PNG. При необходимости увеличьте масштаб шрифта в терминале перед "
        "снимком.",
    )
    _p(
        doc,
        "«Пустое» место под рисунок: поставьте курсор на следующую строку и выполните "
        "вставку изображения — Word разместит Рисунок 3 здесь.",
    )
    doc.add_paragraph()  # визуальный отступ под будущий скриншот
    doc.add_paragraph()

    # --- Этап 5 ---
    doc.add_heading("5-й этап: дополнительное задание и выводы («моделирование»)", level=2)
    _p(
        doc,
        "На заключительном этапе выполняется дополнительное задание: подбор весов w₁, w₂ и "
        "смещения h для линейного порога σ(w₁·x₁ + w₂·x₂ + h), где x₁ — масса, x₂ — рост. "
        "После нормировки признаков получены следующие параметры (в пространстве "
        "нормированных признаков):",
    )
    _p(
        doc,
        f"w₁ = {add_w[0]:.6f}, w₂ = {add_w[1]:.6f}, h = {add_h:.6f}. "
        f"Метки на обучающей выборке после обучения: {add_preds}.",
    )
    _p(
        doc,
        "Проверка: для объектов из таблицы задания классы должны совпадать с эталоном; при "
        "добавлении строки A₄ необходимо заново вызвать процедуру обучения и занести в отчёт "
        "обновлённые w₁, w₂, h и матрицу нормировки (среднее и σ по столбцам).",
    )
    _p(
        doc,
        "Выводы по работе: реализованы три метода безусловной оптимизации; на квадратичной "
        "функции (задание Б) результаты согласуются с аналитическим минимумом; графики "
        "сходимости демонстрируют устойчивое убывание целевой функции; персептрон на "
        "учебной выборке позволяет восстановить разделяющую линию в пространстве признаков.",
    )

    doc.add_heading("Ссылка на исходный код", level=2)
    _p(
        doc,
        f"Полный программный код решения практической части расположен в файле "
        f"«{source_file_hint}». К отчёту рекомендуется приложить распечатку или скриншоты "
        f"данного файла и результатов выполнения (как требует преподаватель). Папка "
        f"«report_generator» используется только для автоматической сборки настоящего "
        f"документа и к перечню приложений по заданию не относится.",
    )

    doc.save(report_path)
