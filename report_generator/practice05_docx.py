"""DOCX для практической работы №5 (вариант 5)."""

from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt


def _p(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def _add_figure(doc: Document, image_path: Path | None, caption: str, width_inches: float = 5.85) -> None:
    if image_path is not None and image_path.is_file():
        doc.add_picture(str(image_path), width=Inches(width_inches))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in cap.runs:
        run.italic = True


def _add_console_placeholder(doc: Document, title: str, instruction: str) -> None:
    doc.add_heading(title, level=3)
    _p(doc, instruction)
    doc.add_paragraph()
    doc.add_paragraph()


def _metrics_table(doc: Document, title: str, mt: dict, mv: dict) -> None:
    doc.add_heading(title, level=3)
    table = doc.add_table(rows=1, cols=5)
    hdr = table.rows[0].cells
    hdr[0].text = "Выборка"
    hdr[1].text = "Accuracy"
    hdr[2].text = "Precision"
    hdr[3].text = "Recall"
    hdr[4].text = "F1"

    row = table.add_row().cells
    row[0].text = "Обучение"
    row[1].text = f"{mt['accuracy']:.4f}"
    row[2].text = f"{mt['precision']:.4f}"
    row[3].text = f"{mt['recall']:.4f}"
    row[4].text = f"{mt['f1']:.4f}"

    row = table.add_row().cells
    row[0].text = "Тест"
    row[1].text = f"{mv['accuracy']:.4f}"
    row[2].text = f"{mv['precision']:.4f}"
    row[3].text = f"{mv['recall']:.4f}"
    row[4].text = f"{mv['f1']:.4f}"


def build_practice05_docx(
    report_path: Path,
    data: dict,
    plot_task1_boundary: Path | None = None,
    plot_task1_cm: Path | None = None,
    plot_task2_series: Path | None = None,
    plot_task2_cm: Path | None = None,
    source_file_hint: str = "neuro_math_Yakimov_var5/task_5/practice05.py",
) -> None:
    report_path.parent.mkdir(parents=True, exist_ok=True)

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    t1 = data["task1"]
    t2 = data["task2"]

    doc.add_heading("Практическая работа №5. Вариант 5", level=1)
    _p(
        doc,
        "Работа выполнена по методическому указанию к практическим занятиям №5. "
        "В первом задании реализована нейросетевая классификация по табличным данным "
        "варианта 5 (таблица 5.16). Во втором задании самостоятельно сформулирована "
        "и решена задача классификации в соответствии с темой варианта 5 из таблицы 5.21 "
        "(прогноз метеорологических условий по историческим признакам).",
    )

    # ---------- Задание 1 ----------
    doc.add_heading("Задание 1. Классификация по таблице 5.16", level=2)

    _p(doc, "1) Постановка задачи.")
    _p(
        doc,
        "Требуется смоделировать нейронную сеть, которая предсказывает необходимость ремонта двигателя "
        "по двум входным признакам: температуре подшипника (°C) и уровню вибрации (мм/с). "
        "Выход интерпретируется как бинарная классификация: «да» — требуется ремонт; «нет» — не требуется.",
    )

    _p(doc, "2) Исходные данные.")
    _p(
        doc,
        "Использованы все 10 наблюдений из таблицы 5.16 методички. В коде классы закодированы численно: "
        "«нет» → 0, «да» → 1. Для контроля обобщения выполнено случайное стратифицированное разбиение "
        "на обучение и тест с долей теста 20% при фиксированном генераторе случайных чисел, чтобы результат "
        "был воспроизводимым.",
    )
    _p(
        doc,
        f"Оказалось в обучении (номера строк по методичке): {t1['train_rows_1based']}. "
        f"Оказалось в тесте: {t1['test_rows_1based']}.",
    )

    _p(doc, "3) Архитектура модели и предобработка.")
    _p(
        doc,
        "Применён многослойный персептрон `MLPClassifier` из scikit-learn с двумя скрытыми слоями (24 и 12 нейронов), "
        "функцией активации ReLU и решателем Adam. Признаки стандартизованы через `StandardScaler` по обучающей части, "
        "после чего те же параметры масштабирования применяются к тесту.",
    )

    _p(doc, "4) Результаты.")
    _metrics_table(doc, "Таблица 1. Метрики качества классификации (задание 1)", t1["metrics_train"], t1["metrics_test"])
    _p(
        doc,
        "Дополнительно сформирована матрица ошибок на тестовой подвыборке (см. рисунок ниже). "
        "Также приведён текстовый `classification_report`, который автоматически выводится программой при запуске скрипта.",
    )

    _p(doc, "5) Иллюстрации.")
    _add_figure(
        doc,
        plot_task1_boundary,
        "Рисунок 1 — Задание 1: карта вероятности класса «да» и разделяющая линия уровня 0.5.",
    )
    _add_figure(
        doc,
        plot_task1_cm,
        "Рисунок 2 — Задание 1: матрица ошибок на тесте (строки — факт, столбцы — прогноз).",
    )

    _add_console_placeholder(
        doc,
        "Рисунок 3 — Скрин консоли для задания 1 (вставить вручную)",
        "Вставьте скриншот терминала с блоком [1/2]: должны быть видны номера строк таблицы в train/test, "
        "метрики accuracy/precision/recall/f1 и матрица ошибок на тесте.",
    )

    # ---------- Задание 2 ----------
    doc.add_heading("Задание 2. Классификация по теме варианта 5 (таблица 5.21)", level=2)

    _p(doc, "1) Формулировка задачи.")
    _p(
        doc,
        "По таблице 5.21 для варианта 5 темой является предсказание метеорологических условий на основе исторических "
        "метеопараметров. В данной работе реализован учебный синтетический временной ряд, имитирующий последовательность "
        "наблюдений по дням: температура воздуха, относительная влажность и атмосферное давление.",
    )
    _p(
        doc,
        "Целевая переменная — бинарный признак наличия осадков на следующий день относительно текущего наблюдения "
        "(переход t → t+1). Таким образом, на вход сети подаются значения метеополей на шаге t, а обучение выполняется "
        "как классификация события «осадки завтра».",
    )

    _p(doc, "2) Формирование выборки.")
    _p(
        doc,
        f"Объём последовательности после формирования признаков и метки: {t2['n_supervised']} наблюдений. "
        "Разбиение на обучение и тест выполняется хронологически (без перемешивания вперёд по времени), что соответствует "
        "реалистичной постановке прогноза по прошлому. Если при выбранной доле обучения на тестовом отрезке отсутствует "
        "один из классов, программа автоматически подбирает близкую долю обучения так, чтобы и на обучении, и на тесте "
        "присутствовали оба класса.",
    )
    _p(
        doc,
        f"Итоговые размеры: обучение — {t2['n_train']} точек, тест — {t2['n_test']} точек; "
        f"эффективная доля обучения составляет примерно {t2['train_ratio_effective']:.1%}. "
        f"Вектор признаков на шаге t: {', '.join(t2['feature_names'])}.",
    )

    _p(doc, "3) Модель.")
    _p(
        doc,
        "Использован `MLPClassifier` с двумя скрытыми слоями (36 и 18 нейронов), активацией tanh и решателем Adam. "
        "Признаки стандартизуются по обучающему отрезку времени. Выбор архитектуры и числа итераций определяется "
        "небольшим экспериментом по сходимости на синтетических данных и может быть уточнён при переходе на реальные "
        "архивы метеонаблюдений.",
    )

    _p(doc, "4) Результаты.")
    _metrics_table(doc, "Таблица 2. Метрики качества классификации (задание 2)", t2["metrics_train"], t2["metrics_test"])
    _p(
        doc,
        "На реальных данных качество обычно ниже из-за шума, неучтённых факторов и нестационарности климата; "
        "здесь синтетическая модель нужна для демонстрации полного конвейера: генерация ряда → признаки → обучение → тест.",
    )

    _p(doc, "5) Иллюстрации.")
    _add_figure(
        doc,
        plot_task2_series,
        "Рисунок 4 — Задание 2: фрагмент ряда влажности и соответствующая бинарная метка осадков (t→t+1).",
    )
    _add_figure(
        doc,
        plot_task2_cm,
        "Рисунок 5 — Задание 2: матрица ошибок на тестовом временном участке.",
    )

    _add_console_placeholder(
        doc,
        "Рисунок 6 — Скрин консоли для задания 2 (вставить вручную)",
        "Вставьте скриншот терминала с блоком [2/2]: должны быть видны объём выборки, описание признаков и цели, "
        "метрики на обучении и тесте, матрица ошибок и classification_report.",
    )

    doc.add_heading("Вывод", level=2)
    _p(
        doc,
        "Выполнены оба задания практики №5 для варианта 5: построена нейросеть для табличной классификации признаков "
        "диагностики двигателя и отдельно реализован учебный конвейер классификации метеосценария по синтетическому ряду. "
        "Получены количественные метрики на отложенном контроле и графические иллюстрации для включения в отчёт.",
    )

    doc.add_heading("Ссылка на исходный код", level=2)
    _p(
        doc,
        f"Рабочий скрипт задания: `{source_file_hint}`. "
        "Генератор отчёта находится в каталоге `report_generator/` и к сдаваемому коду обычно не относится.",
    )

    doc.save(report_path)
