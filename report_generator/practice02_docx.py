"""Развёрнутый DOCX для практической работы №2 (вариант 5)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt


def _p(doc: Document, text: str) -> None:
    doc.add_paragraph(text)


def _code_block(doc: Document, lines: str) -> None:
    p = doc.add_paragraph()
    run = p.add_run(lines.strip("\n"))
    run.font.name = "Courier New"
    run.font.size = Pt(10)
    p.paragraph_format.left_indent = Inches(0.25)


def _add_figure(doc: Document, image_path: Path | None, caption: str, width_inches: float = 5.8) -> None:
    if image_path is not None and image_path.is_file():
        doc.add_picture(str(image_path), width=Inches(width_inches))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in cap.runs:
        run.italic = True


def _table_xy_pairs(doc: Document, title: str, xy: np.ndarray, col_no: bool = True) -> None:
    doc.add_heading(title, level=3)
    n = len(xy)
    table = doc.add_table(rows=1, cols=3 if col_no else 2)
    hdr = table.rows[0].cells
    if col_no:
        hdr[0].text = "№"
        hdr[1].text = "x"
        hdr[2].text = "Y"
    else:
        hdr[0].text = "x"
        hdr[1].text = "Y"
    for i in range(n):
        row = table.add_row().cells
        if col_no:
            row[0].text = str(i + 1)
            row[1].text = f"{float(xy[i, 0]):g}"
            row[2].text = f"{float(xy[i, 1]):g}"
        else:
            row[0].text = f"{float(xy[i, 0]):g}"
            row[1].text = f"{float(xy[i, 1]):g}"


def _table_metrics(doc: Document, title: str, train: dict, test: dict) -> None:
    doc.add_heading(title, level=3)
    table = doc.add_table(rows=1, cols=4)
    hdr = table.rows[0].cells
    hdr[0].text = "Выборка"
    hdr[1].text = "MSE"
    hdr[2].text = "MAE"
    hdr[3].text = "R²"
    for name, m in [("Обучение", train), ("Тест", test)]:
        row = table.add_row().cells
        row[0].text = name
        row[1].text = f"{m['mse']:.6f}"
        row[2].text = f"{m['mae']:.6f}"
        row[3].text = f"{m['r2']:.6f}"


